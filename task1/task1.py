"""
Задание 1. Круговой массив.

Массив из n элементов (1..n) закольцован: после n-го элемента снова идёт 1-й.
Двигаясь по массиву интервалами длины m (начало следующего интервала совпадает
с концом предыдущего), нужно построить путь из начальных элементов полученных
интервалов и остановиться, когда очередной интервал заканчивается на первом
элементе массива.

Программа обрабатывает два таких массива одновременно и выводит объединённый
(конкатенированный) путь: сначала путь первого массива, затем второго.

Параметры передаются аргументами командной строки:
    task1.py n1 m1 n2 m2

Пример:
    task1.py 6 3 5 4   ->  13514253
    task1.py 4 2 6 4   ->  123414
"""
import sys


def build_path(n: int, m: int) -> list:
    """Возвращает путь начальных элементов интервалов длины m
    для кругового массива из n элементов (нумерация с 1)."""
    if n <= 0:
        raise ValueError("n должно быть положительным целым числом")
    if m <= 0:
        raise ValueError("m должно быть положительным целым числом")

    path = []
    start = 1
    while True:
        path.append(start)
        # конец интервала длины m, стартующего в start, по кругу из n элементов
        end = (start - 1 + m - 1) % n + 1
        if end == 1:
            break
        start = end
    return path


def main() -> None:
    args = sys.argv[1:]
    if len(args) != 4:
        print(
            "Использование: task1.py n1 m1 n2 m2",
            file=sys.stderr,
        )
        sys.exit(1)

    try:
        n1, m1, n2, m2 = (int(a) for a in args)
    except ValueError:
        print("Все параметры должны быть целыми числами", file=sys.stderr)
        sys.exit(1)

    path1 = build_path(n1, m1)
    path2 = build_path(n2, m2)

    result = "".join(str(x) for x in path1) + "".join(str(x) for x in path2)
    print(result)


if __name__ == "__main__":
    main()
